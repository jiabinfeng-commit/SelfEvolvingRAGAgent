# -*- coding: utf-8 -*-
"""
阶段 5：Agent 自愈（Self-Healing）—— 项目名 "Self-Evolving" 的最小落地形态

为什么需要它？（这一步不是拍脑袋加的，是阶段 4 评估逼出来的）
------------------------------------------------------------------
阶段 4 的 A/B 评估暴露了真正的瓶颈：#40 / #42 两题的 recall_top3=✓
（正确文档明明被召回到了），但模型仍然回答「根据提供的资料无法回答」。
也就是说：**召回没问题，是模型太保守** —— 阶段 2 那句抗幻觉指令
「无据说不知道」被**过度触发**了（over-refusal）。

自愈思路（和人类排查故障一模一样）：
    检测到「模型拒答」 + 「召回质量其实不差」
        → 判定为「误拒」（而不是真的没有答案）
        → 换策略重试一次：
            ① 换宽松版 system prompt（鼓励先尝试作答，别轻易说不知道）
            ② 扩大召回 top_k（给它更多素材）
    重试后仍然拒答 / 仍然错，就保持原样 —— 不自欺欺人，也不无限重试烧 token。

这就是"自进化"的最小可用形态：系统根据**自己的失败信号**（拒答）自动调整行为，
而不是靠人去读日志再改代码。

为什么必须设阈值？（关键设计，防止把"真拒答"救成幻觉）
--------------------------------------------------
评测集里有 8 道 unanswerable（语料里真没答案），模型拒答是**正确行为**。
如果不加区分地"见拒答就重试"，就会把这 8 题也强行逼出答案 → 幻觉率飙升，
阶段 3 辛苦测出来的 100% 拒答正确率会直接崩掉。

所以自愈的触发条件必须是**两个同时满足**：
    1. 模型确实在拒答（is_refusal）
    2. 召回质量其实不差（top1 相似度 ≥ SELF_HEAL_SCORE_THRESHOLD）
       —— 说明"资料里大概率有答案，是模型没敢答"
只有这时才重试。召回分低 = 真的没有答案 = 不该救。
"""
from typing import Optional


# 判定「拒答」的关键词：命中任一即认为模型在拒答
# （用关键词而不是再调一次 LLM 判断，是为了省钱省时间：50 题 × 2 次调用已经很慢了）
REFUSAL_PATTERNS = [
    "无法回答", "无法提供", "不能回答", "不能提供",
    "没有提供", "没有提到", "未提及", "没有涉及",
    "资料中不存在", "语料中不存在", "资料中没有", "上下文没有", "上下文中没有",
    "根据提供的资料无法", "根据提供的上下文无法",
    "不知道", "无法确定", "无相关信息",
]

# 召回质量阈值：top1 余弦相似度低于这个值 → 认为确实没召回，不该自愈
# 参考阶段 1 数据：正确命中通常 0.70+，边缘约 0.55~0.65，噪声 <0.5
SELF_HEAL_SCORE_THRESHOLD = 0.5

# 自愈时把 top_k 放大几倍（给它更多素材，扩大"找到答案"的概率）
SELF_HEAL_TOPK_MULT = 2


def is_refusal(answer: str) -> bool:
    """
    判断模型回答是不是在拒答。

    - 空回答（或生成失败留下的占位）也算拒答 —— 因为对下游来说效果一样：没给出答案。
    - 用关键词匹配而不是再调一次 LLM 判断：一次评估 50 题已经要调 100 次 LLM，
      再加一层判断会翻倍耗时和 token，性价比太低。
    """
    if not answer or not answer.strip():
        return True
    return any(p in answer for p in REFUSAL_PATTERNS)


def should_heal(answer: str, top_score: Optional[float]) -> bool:
    """
    是否该触发自愈。两个条件同时满足才救：
      1. 模型在拒答
      2. 召回质量其实不差（top1 相似度 ≥ 阈值）

    :param answer:    模型首轮生成的答案
    :param top_score: 首轮召回里最相关的那一块的相似度（None 表示压根没召回）
    """
    if not is_refusal(answer):
        return False                      # 没拒答 → 不需要救
    if top_score is None:
        return False                      # 一条都没召回 → 那确实是没有答案
    return top_score >= SELF_HEAL_SCORE_THRESHOLD
